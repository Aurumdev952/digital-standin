"""Mixes ESC-50 'laughing' clips into the meeting recording at known times and writes exact labels.

Usage: python3 -I scripts/make-laugh-mix.py   (from the repo root; needs ffmpeg and curl)
Output: test-media/meeting-laughs.wav and test-media/meeting-laughs.labels.toml
ESC-50 (Piczak 2015) is CC BY-NC 3.0: fine for local evaluation, not for redistribution.
"""
import array, csv, io, math, os, random, subprocess, sys, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MEDIA = os.path.join(ROOT, "test-media")
ESC = os.path.join(MEDIA, "esc50")
BASE = "https://raw.githubusercontent.com/karolpiczak/ESC-50/master"
RATE = 16000


def pcm16k(path_or_url):
    data = subprocess.run(["ffmpeg", "-v", "error", "-i", path_or_url, "-ac", "1", "-ar", str(RATE), "-f", "f32le", "-"],
                          check=True, capture_output=True).stdout
    return array.array("f", data)


def rms(xs):
    return math.sqrt(sum(x * x for x in xs) / max(1, len(xs)))


def onset_and_end(x):
    """First and last 20 ms frame within 20 dB of the clip's loudest frame."""
    hop = RATE // 50
    frames = [rms(x[i:i + hop]) for i in range(0, len(x) - hop, hop)]
    peak = max(frames)
    loud = [i for i, f in enumerate(frames) if f >= peak * 0.1]
    return loud[0] * hop / RATE, (loud[-1] + 1) * hop / RATE


def main():
    os.makedirs(ESC, exist_ok=True)
    meta = list(csv.DictReader(io.StringIO(urllib.request.urlopen(f"{BASE}/meta/esc50.csv").read().decode())))
    laughs = [m["filename"] for m in meta if m["category"] == "laughing"]
    random.Random(7).shuffle(laughs)
    picked = laughs[:12]
    meeting = pcm16k(os.path.join(MEDIA, "meeting.wav"))
    speech_level = rms(meeting)
    out = array.array("f", meeting)
    labels = []
    for i, name in enumerate(picked):
        local = os.path.join(ESC, name)
        if not os.path.exists(local):
            urllib.request.urlretrieve(f"{BASE}/audio/{name}", local)
        clip = pcm16k(local)
        on, off = onset_and_end(clip)
        start = 15.0 + i * 23.0 + random.Random(i).uniform(-3, 3)
        gain = speech_level / max(rms(clip[int(on * RATE):int(off * RATE)]), 1e-6)
        s = int(start * RATE)
        for j, v in enumerate(clip):
            if s + j < len(out):
                out[s + j] = max(-1.0, min(1.0, out[s + j] + v * gain))
        labels.append((name, start + on, start + off))
    wav = os.path.join(MEDIA, "meeting-laughs.wav")
    subprocess.run(["ffmpeg", "-v", "error", "-y", "-f", "f32le", "-ar", str(RATE), "-ac", "1", "-i", "-", wav],
                   input=out.tobytes(), check=True)
    with open(os.path.join(MEDIA, "meeting-laughs.labels.toml"), "w") as f:
        f.write("# meeting.wav with 12 ESC-50 'laughing' clips mixed in at speech level.\n")
        f.write("# Generated by scripts/make-laugh-mix.py; onsets are exact (energy within 20 dB of peak).\n\n")
        for name, a, b in labels:
            f.write(f'[[event]]\nkind = "laughter"\nstart = {a:.2f}\nend = {b:.2f}\n# {name}\n\n')
    print(f"wrote {wav} with {len(labels)} laughs")


if __name__ == "__main__":
    sys.exit(main())
